/**
 * The "Escape hatches" table in docs/platform/configuration.md is generated
 * from the operational-mode register, packages/engine/src/lib/operational-modes.ts
 * (ADR 0058 decision 4).
 *
 * Run: `bun run scripts/gen-operational-modes.ts`; `--check` (CI,
 * `check:modes`) fails when the table is stale, or when engine code other than
 * the register reads a registered variable (`.NAME` or `['NAME']`) — the
 * register must stay the only reader, so a new hatch cannot exist without an
 * entry. A read through a helper taking the name as an argument is not seen.
 * It also fails on a `NODE_ENV` compared with `'production'` outside the
 * register: unset is production (ADR 0058, owner 2026-11-17), and such a
 * comparison reads unset as development — every guard asks `isProduction()`.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { MODES, type Mode } from '../packages/engine/src/lib/operational-modes.ts';

const ROOT = join(import.meta.dir, '..');
const DOC = join(ROOT, 'docs/platform/configuration.md');
const ENGINE_SRC = join(ROOT, 'packages/engine/src');
const REGISTER = join(ENGINE_SRC, 'lib/operational-modes.ts');
const BEGIN =
  '<!-- BEGIN generated by scripts/gen-operational-modes.ts — edit the register, not this table -->';
const END = '<!-- END generated: operational modes -->';

const cell = (s: string) => s.replace(/\|/g, '\\|');

function table(): string {
  const rows = (Object.entries(MODES) as [string, Mode][]).map(
    ([name, m]) =>
      `| \`${name}\` | ${cell(m.weakens)} | ${cell(m.when)} | ${m.class} | ${cell(m.removal)} |`,
  );
  return [
    BEGIN,
    '',
    '| Mode | What it turns off | When it is defensible | Class | Removal |',
    '|------|-------------------|-----------------------|-------|---------|',
    ...rows,
    '',
    END,
  ].join('\n');
}

function withTable(doc: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`markers not found in ${relative(ROOT, DOC)}`);
  return doc.slice(0, a) + table() + doc.slice(b + END.length);
}

// `NODE_ENV === 'production'`, `!= "production"`, `'production' !== env.NODE_ENV`, `['NODE_ENV']` too.
const PROD = `['"\`]production['"\`]`;
const NODE_ENV = `(?:\\b(?:NODE_ENV|nodeEnv)\\b|\\[\\s*['"\`]NODE_ENV['"\`]\\s*\\])`;
const PROD_COMPARE = new RegExp(
  `${NODE_ENV}\\s*[!=]==?\\s*${PROD}|${PROD}\\s*[!=]==?\\s*[\\w.$?]*${NODE_ENV}`,
  'g',
);

/** Engine code, tests and fixtures aside, that reads a registered variable. */
function directReads(): string[] {
  const names = (Object.entries(MODES) as [string, Mode][])
    .filter(([, m]) => m.on && m.class !== 'platform')
    .map(([n]) => n);
  const re = new RegExp(
    `(?:\\.(${names.join('|')})\\b|\\[\\s*['"\`](${names.join('|')})['"\`]\\s*\\])`,
    'g',
  );
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const e of readdirSync(dir)) {
      if (e === 'node_modules' || e === 'tests' || e === 'testing' || e.endsWith('-dist')) continue;
      const p = join(dir, e);
      if (statSync(p).isDirectory()) walk(p);
      else if (p.endsWith('.ts') && !p.includes('.test.') && p !== REGISTER) {
        // Comments only where one starts a line or follows code after a space:
        // a naive `/*` strip also eats from `'/api/*'` to the next comment.
        const code = readFileSync(p, 'utf8')
          .replace(/^\s*\/\*[\s\S]*?\*\//gm, '')
          .replace(/(^|\s)\/\/[^\n]*/g, '$1');
        for (const m of code.matchAll(re)) out.push(`${relative(ROOT, p)}: ${m[1] ?? m[2]}`);
        for (const m of code.matchAll(PROD_COMPARE))
          out.push(`${relative(ROOT, p)}: ${m[0]} (ask isProduction())`);
      }
    }
  };
  walk(ENGINE_SRC);
  return out;
}

const doc = readFileSync(DOC, 'utf8');
const fresh = withTable(doc);

if (process.argv.includes('--check')) {
  let failed = false;
  if (fresh !== doc) {
    console.error(
      '[operational-modes] FAIL — the Escape hatches table in docs/platform/configuration.md ' +
        'does not match the register. Run: bun run scripts/gen-operational-modes.ts',
    );
    failed = true;
  }
  const reads = directReads();
  if (reads.length > 0) {
    console.error(
      '[operational-modes] FAIL — read outside the register; use modeValue() or isProduction() from lib/operational-modes.ts:',
    );
    for (const r of reads) console.error(`  ${r}`);
    failed = true;
  }
  if (failed) process.exit(1);
  console.log(`[operational-modes] OK — ${Object.keys(MODES).length} modes, one reader.`);
} else {
  writeFileSync(DOC, fresh);
  console.log(`[operational-modes] wrote ${relative(ROOT, DOC)}`);
}
