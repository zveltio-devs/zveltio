-- 109_drop_quality_engine_tables.sql
--
-- `zv_quality_scans` and `zv_quality_issues` came with the engine's own data
-- quality feature (025_quality, squashed into 001). The feature moved to the
-- `analytics/quality` extension in 1.0.5, whose migrations re-declared both
-- tables and added the `tenant_id` column and the RLS policies. Nothing in the
-- engine has read or written them since.
--
-- `analytics/quality` 2.0.0 keeps its scans and issues in the declared
-- collections `quality_scans` and `quality_issues` (`zvd_` tables the engine
-- creates and owns) and ships no SQL. A fresh install now got two engine tables
-- with no tenant column, no policy and no reader, and an upgraded one kept the
-- 1.x rows nothing reads any more. Both go. Their rows are scan output — derived
-- from the collections they scanned, regenerated by running a scan — and 2.0.0
-- does not carry them over.
--
-- CASCADE: on a 1.x install `zvd_quality_remediations.issue_id` (and
-- `zvd_quality_scores.scan_id`, when its 004 has not run) is a foreign key into
-- these tables, which a plain DROP refuses. CASCADE drops those constraints,
-- not the tables that hold them: the remaining 1.x `zvd_quality_*` tables stay,
-- as 2.0.0 leaves them.
--
-- An installed 1.x `analytics/quality` loses its scans and issues with this
-- migration; 2.0.0 is the version that runs on this engine.

-- squawk-ignore-file ban-drop-table

DROP TABLE IF EXISTS zv_quality_issues CASCADE;
DROP TABLE IF EXISTS zv_quality_scans CASCADE;

